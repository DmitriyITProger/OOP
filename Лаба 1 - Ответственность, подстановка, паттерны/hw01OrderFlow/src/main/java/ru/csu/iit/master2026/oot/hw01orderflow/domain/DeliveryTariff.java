package ru.csu.iit.master2026.oot.hw01orderflow.domain;

/**
 * Тариф доставки: сколько стоит и сколько дней везти.
 *
 * <p>Паттерн «Стратегия»: {@link Order} — контекст, тариф — сменяемый алгоритм.
 * Новый тариф — новый класс; код, который считает доставку, при этом не меняется.
 */
public interface DeliveryTariff {

    Money cost(Money goods);

    int days();

    /** Экспресс ли это: так тариф сам говорит отчётам, считать ли его экспрессом. По умолчанию — нет. */
    default boolean express() {
        return false;
    }

    /**
     * Обещание клиенту для уведомления о новом заказе, например «привезём завтра.».
     * Тариф сам отвечает за свой текст; для обычных тарифов обещания нет.
     */
    default String promise() {
        return "";
    }
}
